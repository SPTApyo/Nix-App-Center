//! Generation of the Onyx files (`onyx-home.nix`, `onyx-system.nix`) and applying
//! the configuration.
//!
//! **Onyx never overwrites anything.** It owns these two files, fully generated
//! from the manifest, and touches no file written by the user; its only intrusion
//! is the `imports` line added once by [`crate::config_attach`], with explicit
//! consent.
//!
//! A **plain** app is an entry aggregated into the user package list. A **promoted** app
//! (the user edited its Nix block) is emitted as a region delimited by markers,
//! which makes it individually findable, replaceable and removable.

use crate::config_layout::{current_user, detect, Layout, LayoutKind};
use crate::manifest::KeptEntry;
use std::process::Command;

/// How the user scope file is written, decided by the layout.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum HomeShape {
    /// A home-manager module (standalone home-manager).
    HomeManager,
    /// A NixOS module wrapping home-manager options in `home-manager.users.<user>`.
    NixosHm(String),
    /// A NixOS module without home-manager: `home.packages` does not exist
    /// there, packages go to `users.users.<user>.packages`.
    NixosUser(String),
}

impl HomeShape {
    pub(crate) fn of(layout: &Layout) -> Self {
        let nixos = matches!(
            layout.kind,
            LayoutKind::NixosFlake { .. } | LayoutKind::NixosLegacy { .. }
        );
        match (nixos, &layout.hm_user) {
            (true, Some(user)) => Self::NixosHm(user.clone()),
            (true, None) => Self::NixosUser(current_user()),
            (false, _) => Self::HomeManager,
        }
    }

    fn packages_option(&self) -> String {
        match self {
            Self::NixosUser(user) => format!("users.users.\"{user}\".packages"),
            _ => "home.packages".to_string(),
        }
    }
}

/// What a block holds when an app is promoted from a plain entry: exactly what
/// the plain entry did. The user starts from what exists and edits it; nothing
/// disappears without them seeing it.
pub fn default_home_block(layout: &Layout, attr: &str) -> String {
    default_block(&HomeShape::of(layout), attr)
}

fn default_block(shape: &HomeShape, attr: &str) -> String {
    format!("{} = [ pkgs.{attr} ];", shape.packages_option())
}

fn header(warn: &str) -> String {
    format!("# {warn}\n# Generated by Onyx, do not edit by hand.\n")
}

/// Opens the region of a promoted app. Markers keep the diff readable and the
/// removal safe.
fn begin(attr: &str) -> String {
    format!("# onyx:begin {attr}")
}

fn end(attr: &str) -> String {
    format!("# onyx:end {attr}")
}

/// Indents every non-empty line by `n` spaces.
fn indent(body: &str, n: usize) -> String {
    let pad = " ".repeat(n);
    body.lines()
        .map(|l| {
            if l.trim().is_empty() {
                String::new()
            } else {
                format!("{pad}{l}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// The block of a promoted app, wrapped as a **standalone Nix module**.
///
/// This is what makes free editing possible: two blocks (or a block and the
/// aggregated list) both defining `home.packages` are *merged* by the module
/// system, while side by side in one attrset they would be a redefinition,
/// "attribute 'home.packages' already defined", and the file would not even parse.
fn module_region(attr: &str, block: &str) -> String {
    format!(
        "{}\n({{ pkgs, lib, config, ... }}: {{\n{}\n}})\n{}",
        begin(attr),
        indent(block.trim_end(), 2),
        end(attr)
    )
}

/// The `imports` list of promoted apps. Empty when there are none.
fn imports_list(regions: &[String]) -> String {
    if regions.is_empty() {
        return String::new();
    }
    let mut out = String::from("imports = [\n");
    for r in regions {
        out.push_str(&indent(r, 2));
        out.push('\n');
    }
    out.push_str("];\n");
    out
}

/// Regions of promoted apps for a given scope, sorted (stable diff).
fn regions(kept: &[KeptEntry], scope: fn(&KeptEntry) -> Option<&String>) -> Vec<String> {
    let mut promues: Vec<&KeptEntry> = kept.iter().filter(|e| scope(e).is_some()).collect();
    promues.sort_by(|a, b| a.package.attr.cmp(&b.package.attr));
    promues
        .iter()
        .map(|e| module_region(&e.package.attr, scope(e).map(String::as_str).unwrap_or("")))
        .collect()
}

/// Body of the user scope: modules of promoted apps, then the aggregated list
/// of plain apps.
fn home_body(kept: &[KeptEntry], packages: &str) -> String {
    let mut simples: Vec<&str> = kept
        .iter()
        .filter(|e| e.home_nix.is_none())
        .map(|e| e.package.attr.as_str())
        .collect();
    simples.sort_unstable();
    simples.dedup();

    let mut out = imports_list(&regions(kept, |e| e.home_nix.as_ref()));
    if !out.is_empty() {
        out.push('\n');
    }

    if simples.is_empty() {
        out.push_str(&format!("{packages} = with pkgs; [ ];\n"));
    } else {
        out.push_str(&format!("{packages} = with pkgs; [\n"));
        for attr in simples {
            out.push_str(&format!("  {attr}\n"));
        }
        out.push_str("];\n");
    }
    out
}

/// Body of the system scope: modules only (no "plain list" equivalent; system
/// options are only written deliberately).
fn system_body(kept: &[KeptEntry]) -> String {
    imports_list(&regions(kept, |e| e.system_nix.as_ref()))
}

/// Renders `onyx-home.nix`.
///
/// Its **shape depends on the layout**: when home-manager is a NixOS module, the
/// file is a *NixOS* module wrapping its content in `home-manager.users.<user>`,
/// which allows attaching it to the top-level `imports` of `configuration.nix`,
/// the safest splice. With standalone home-manager, it is a plain HM module.
/// On NixOS without home-manager, it is a NixOS module using `users.users`.
pub(crate) fn render_home(kept: &[KeptEntry], shape: &HomeShape) -> String {
    let body = home_body(kept, &shape.packages_option());
    let mut out = header("User scope.");
    out.push_str("{ pkgs, lib, config, ... }:\n{\n");
    match shape {
        HomeShape::NixosHm(user) => {
            out.push_str(&format!("  home-manager.users.{user} = {{\n"));
            out.push_str(&indent(&body, 4));
            out.push_str("\n  };\n");
        }
        HomeShape::HomeManager | HomeShape::NixosUser(_) => {
            out.push_str(&indent(&body, 2));
            out.push('\n');
        }
    }
    out.push_str("}\n");
    out
}

/// Renders `onyx-system.nix`. Generated even when empty: the import line must
/// never point to nothing.
pub(crate) fn render_system(kept: &[KeptEntry]) -> String {
    let body = system_body(kept);
    let mut out = header("System scope (NixOS).");
    out.push_str("{ pkgs, lib, config, ... }:\n{\n");
    if !body.trim().is_empty() {
        out.push_str(&indent(body.trim_end(), 2));
        out.push('\n');
    }
    out.push_str("}\n");
    out
}

/// Regenerates the Onyx files from the manifest, for the detected layout.
///
/// When the layout is unknown, **nothing is written**: Onyx does not leave an
/// orphan file that nothing imports (precisely the original bug). The manifest
/// itself is kept; the front end warns the user.
pub(crate) fn sync_config(kept: &[KeptEntry]) -> std::io::Result<()> {
    sync_to(&detect(), kept)
}

pub(crate) fn sync_to(layout: &Layout, kept: &[KeptEntry]) -> std::io::Result<()> {
    if let Some(home) = &layout.home {
        let body = render_home(kept, &HomeShape::of(layout));
        crate::paths::write_atomic(&home.onyx_file, body.as_bytes())?;
        crate::paths::track_in_git(&home.onyx_file);
    }
    if let Some(system) = &layout.system {
        let body = render_system(kept);
        crate::paths::write_atomic(&system.onyx_file, body.as_bytes())?;
        crate::paths::track_in_git(&system.onyx_file);
    }
    Ok(())
}

// ── Applying ──────────────────────────────────────────────────────────────────

/// What happened when applying the configuration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ApplyOutcome {
    /// Ran to completion, output captured (no `sudo` case).
    Done(String),
    /// Started in a terminal: the build is long and asks for a password, so it
    /// must stay visible and interruptible. The user follows the output there.
    Launched,
    /// `sudo` needed but no terminal found. The front end copies the argv and
    /// says so; the core does not touch the clipboard.
    NoTerminal(Vec<String>),
    /// Unknown layout: Onyx does not know where your config is and does not guess.
    UnknownLayout,
}

/// Applies the configuration with **the command matching the real layout**.
///
/// It used to hardcode `home-manager switch`, wrong on a NixOS install where
/// home-manager is a module (no standalone binary), i.e. the most common case.
pub fn apply_config() -> std::io::Result<ApplyOutcome> {
    let layout = detect();
    if !layout.is_usable() {
        return Ok(ApplyOutcome::UnknownLayout);
    }
    run_apply(&layout.apply)
}

pub(crate) fn run_apply(argv: &[String]) -> std::io::Result<ApplyOutcome> {
    let Some((bin, args)) = argv.split_first() else {
        return Ok(ApplyOutcome::UnknownLayout);
    };

    // `sudo` needs a tty for the password: capturing it through a pipe would
    // make it fail (or hang) silently. So a real terminal is used, where the
    // user sees the build and can interrupt it.
    if bin == "sudo" {
        return match crate::launch::spawn_in_terminal(argv)? {
            crate::launch::ShellOutcome::Spawned => Ok(ApplyOutcome::Launched),
            crate::launch::ShellOutcome::NoTerminal => Ok(ApplyOutcome::NoTerminal(argv.to_vec())),
        };
    }

    let out = match Command::new(bin).args(args).output() {
        Ok(o) => o,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return Err(std::io::Error::new(
                std::io::ErrorKind::NotFound,
                format!("“{bin}” not found: Onyx cannot apply your configuration."),
            ));
        }
        Err(e) => return Err(e),
    };

    if out.status.success() {
        Ok(ApplyOutcome::Done(
            String::from_utf8_lossy(&out.stdout)
                .lines()
                .last()
                .unwrap_or("")
                .trim()
                .to_string(),
        ))
    } else {
        Err(std::io::Error::other(
            String::from_utf8_lossy(&out.stderr).into_owned(),
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Package;

    fn simple(attr: &str) -> KeptEntry {
        KeptEntry::simple(Package::from_attr(attr))
    }

    fn promue(attr: &str, home: Option<&str>, system: Option<&str>) -> KeptEntry {
        KeptEntry {
            package: Package::from_attr(attr),
            home_nix: home.map(str::to_string),
            system_nix: system.map(str::to_string),
        }
    }

    #[test]
    fn home_aggregates_simple_entries_sorted() {
        let kept = vec![simple("ripgrep"), simple("firefox")];
        let out = render_home(&kept, &HomeShape::HomeManager);
        assert!(out.contains("home.packages = with pkgs; ["));
        let fx = out.find("firefox").unwrap();
        let rg = out.find("ripgrep").unwrap();
        assert!(fx < rg, "rendering must be sorted for a stable diff");
        assert!(!out.contains("onyx:begin"), "no promoted app here");
    }

    #[test]
    fn home_wraps_in_hm_user_when_module() {
        let out = render_home(&[simple("firefox")], &HomeShape::NixosHm("alice".into()));
        assert!(out.contains("home-manager.users.alice = {"));
        assert!(out.contains("home.packages"));
    }

    #[test]
    fn home_is_plain_hm_module_when_standalone() {
        let out = render_home(&[simple("firefox")], &HomeShape::HomeManager);
        assert!(!out.contains("home-manager.users"));
        assert!(out.contains("home.packages"));
    }

    #[test]
    fn nixos_without_home_manager_uses_user_packages() {
        // `home.packages` does not exist in NixOS: the rebuild would fail.
        let out = render_home(&[simple("hello")], &HomeShape::NixosUser("alice".into()));
        assert!(out.contains("users.users.\"alice\".packages = with pkgs; ["));
        assert!(!out.contains("home.packages"));
        assert_eq!(
            default_block(&HomeShape::NixosUser("alice".into()), "hello"),
            "users.users.\"alice\".packages = [ pkgs.hello ];"
        );
    }

    #[test]
    fn shape_follows_the_layout() {
        let layout = |kind, hm_user: Option<&str>| Layout {
            kind,
            home: None,
            system: None,
            apply: vec![],
            hm_user: hm_user.map(str::to_string),
        };
        let dir = std::path::PathBuf::from("/x");
        assert_eq!(
            HomeShape::of(&layout(
                LayoutKind::NixosLegacy { dir: dir.clone() },
                Some("bob")
            )),
            HomeShape::NixosHm("bob".into())
        );
        assert!(matches!(
            HomeShape::of(&layout(LayoutKind::NixosLegacy { dir: dir.clone() }, None)),
            HomeShape::NixosUser(_)
        ));
        assert_eq!(
            HomeShape::of(&layout(LayoutKind::HmStandalone { dir }, None)),
            HomeShape::HomeManager
        );
    }

    #[test]
    fn promoted_entry_is_a_delimited_region_and_leaves_the_list() {
        let kept = vec![
            simple("firefox"),
            promue(
                "quickshare",
                Some("services.quickshare.enable = true;"),
                None,
            ),
        ];
        let out = render_home(&kept, &HomeShape::HomeManager);
        assert!(out.contains("# onyx:begin quickshare"));
        assert!(out.contains("services.quickshare.enable = true;"));
        assert!(out.contains("# onyx:end quickshare"));
        // Promoted = out of the aggregated list: its module decides from now on.
        let list = out.split("home.packages").nth(1).unwrap();
        assert!(!list.contains("quickshare"));
        assert!(list.contains("firefox"));
    }

    /// The default promoted block redefines `home.packages`, which the aggregated
    /// list already defines. In one attrset Nix refuses ("attribute already
    /// defined") and the file does not even parse. So each promoted app must be a
    /// separate module, merged by the module system.
    #[test]
    fn promoted_block_does_not_redefine_the_aggregate_list() {
        let kept = vec![
            simple("firefox"),
            promue(
                "quickshare",
                Some(&default_block(&HomeShape::HomeManager, "quickshare")),
                None,
            ),
        ];
        let out = render_home(&kept, &HomeShape::NixosHm("alice".into()));

        assert!(
            out.contains("imports = ["),
            "promoted apps go through imports"
        );
        assert!(
            out.contains("({ pkgs, lib, config, ... }: {"),
            "each region is a standalone module"
        );

        // One `home.packages` definition per attrset: the promoted module's is in
        // its own, the aggregated list's in the parent attrset.
        let region = out
            .split("# onyx:begin quickshare")
            .nth(1)
            .unwrap()
            .split("# onyx:end")
            .next()
            .unwrap();
        assert!(region.contains("home.packages = [ pkgs.quickshare ];"));
        assert!(region.contains("({ pkgs, lib, config, ... }: {"));
    }

    #[test]
    fn default_block_reproduces_what_the_simple_entry_did() {
        // Promoting must not make anything vanish silently: start from what exists.
        assert_eq!(
            default_block(&HomeShape::HomeManager, "quickshare"),
            "home.packages = [ pkgs.quickshare ];"
        );
    }

    #[test]
    fn system_holds_only_regions() {
        let kept = vec![
            simple("firefox"),
            promue(
                "quickshare",
                None,
                Some("networking.firewall.allowedTCPPorts = [ 8080 ];"),
            ),
        ];
        let out = render_system(&kept);
        assert!(out.contains("# onyx:begin quickshare"));
        assert!(out.contains("networking.firewall.allowedTCPPorts = [ 8080 ];"));
        assert!(
            !out.contains("firefox"),
            "a plain app writes nothing on the system side"
        );
    }

    #[test]
    fn empty_files_are_still_valid_nix() {
        assert!(render_system(&[]).contains("{ pkgs, lib, config, ... }:"));
        assert!(
            render_home(&[], &HomeShape::HomeManager).contains("home.packages = with pkgs; [ ];")
        );
    }
}
